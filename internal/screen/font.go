// textWidth is how wide s is at scale (5 columns and a gap of 1 per character).
func textWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return (n*6 - 1) * scale
}

// text draws s with its top-left at (x, y); unknown characters are left out.
func text(img *image.RGBA, s string, x, y, scale int, c color.RGBA) {
	u := &image.Uniform{c}
	for _, r := range strings.ToUpper(s) {
		g, ok := glyphs[r]
		if !ok {
			continue
		}
		for row, line := range g {
			for col, ch := range line {
				if ch == '#' {
					px := x + col*scale
					py := y + row*scale
					draw.Draw(img, image.Rect(px, py, px+scale, py+scale), u, image.Point{}, draw.Src)
				}
			}
		}
		x += 6 * scale
	}
}

// centered draws s centered on cx.
func centered(img *image.RGBA, s string, cx, y, scale int, c color.RGBA) {
	text(img, s, cx-textWidth(s, scale)/2, y, scale, c)
}
